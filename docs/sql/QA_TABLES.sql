CREATE INDEX IDX_QA_REC_LEVEL ON QA_INSPECT_RECORD(RISK_LEVEL);
CREATE INDEX IDX_QA_REC_BY ON QA_INSPECT_RECORD(INSPECT_BY);
CREATE INDEX IDX_QA_REC_STATUS ON QA_INSPECT_RECORD(RECORD_STATUS);
